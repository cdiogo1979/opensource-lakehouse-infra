"""The shared workload Python environment: the lock, the venv check, and product extras.

  workload_python.py check-lock LOCK
  workload_python.py check-venv PYTHON --lock LOCK [--allow-extra]
  workload_python.py check-extras FILE --lock LOCK
  workload_python.py install-extras [FILE] --lock LOCK [--target DIR] [--reset]

Exit 0 when fine, 1 with one line per problem, 2 for a usage error. Standard library
only, on Python 3.10: it runs in the Spark runtime image, the Jupyter image, and
Jenkins. Rules: BR-L (lock), BR-V (venv check), BR-E (extras lines), BR-R
(resolution and installs), BR-J (the Jupyter user folder).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

LOCK_HEADER = "# Generated by scripts/setup/lock-workload-python.sh from requirements.in. Do not edit."
# pyspark and py4j come from /opt/spark; the packaging tools belong to the venv itself.
PLATFORM_MANAGED = frozenset({"pyspark", "py4j", "pip", "setuptools", "wheel"})
PYTHON_VERSION = "3.10"
MAX_EXTRAS_BYTES = 64 * 1024
MAX_EXTRAS_REQUIREMENTS = 200
STAMP_NAME = ".lakehouse-lock.sha256"

NAME = r"[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?"
NAME_RE = re.compile(NAME)
VERSION_RE = re.compile(r"[A-Za-z0-9.+!_-]+")
LOCK_LINE = re.compile(rf"(?P<name>{NAME})==(?P<version>[A-Za-z0-9.+!_-]+)")
SPECIFIER = r"(?:~=|==|!=|<=|>=|<|>)\s*[A-Za-z0-9.*+!_-]+"
REQUIREMENT = re.compile(
    rf"(?P<name>{NAME})\s*"
    rf"(?:\[\s*(?:{NAME}(?:\s*,\s*{NAME})*)?\s*\])?\s*"
    rf"(?:{SPECIFIER}(?:\s*,\s*{SPECIFIER})*)?\s*"
    r"(?:;.+)?"
)
INLINE_COMMENT = re.compile(r"\s+#.*$")
# pip accepts only the exact --platform tags given, so list every one the runtime
# (aarch64, glibc 2.31) supports.
PLATFORM_TAGS = ["manylinux2014_aarch64"] + [f"manylinux_2_{minor}_aarch64" for minor in range(17, 32)]
PIP_COMMON = ["--disable-pip-version-check", "--no-input", "--no-cache-dir"]


def normalize_name(name: str) -> str:
    """PEP 503 normalization: lowercase, and each run of -, _ or . becomes -."""
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_lock(text: str, source: str = "requirements.lock") -> tuple[dict[str, str], list[str]]:
    """Read a lock into {normalized name: version}; any other line is a problem (BR-L1 to BR-L5)."""
    lock: dict[str, str] = {}
    problems: list[str] = []
    lines = text.splitlines()
    if not lines or lines[0] != LOCK_HEADER:
        problems.append(f"{source}:1: the first line must be the generator header")
    for number, line in enumerate(lines, start=1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        match = LOCK_LINE.fullmatch(stripped)
        if not match:
            problems.append(f"{source}:{number}: not a name==version line")
            continue
        name = normalize_name(match["name"])
        if name in PLATFORM_MANAGED:
            problems.append(f"{source}:{number}: {name} is provided by the platform and must not be locked")
        elif name in lock:
            problems.append(f"{source}:{number}: {name} appears twice")
        else:
            lock[name] = match["version"]
    if not lock and not problems:
        problems.append(f"{source}: the lock is empty")
    return lock, problems


def render_lock(packages: dict[str, str]) -> str:
    """The lock text for {name: version}: the header, then one line per package by normalized name."""
    lines = [f"{name}=={packages[name]}" for name in sorted(packages, key=normalize_name)]
    return "\n".join([LOCK_HEADER, *lines]) + "\n"


def parse_freeze(text: str) -> dict[str, str]:
    """Read ``pip freeze`` output into {normalized name: version}; a direct reference keeps its text."""
    installed: dict[str, str] = {}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith(("#", "-")):
            continue
        if "==" in stripped:
            name, version = stripped.split("==", 1)
        elif " @ " in stripped:
            name, version = stripped.split(" @ ", 1)
            version = "@ " + version
        else:
            name, version = stripped, ""
        installed[normalize_name(name.strip())] = version.strip()
    return installed


def compare(lock: dict[str, str], installed: dict[str, str], allow_extra: bool = False) -> list[str]:
    """Differences between the lock and an installed set (BR-V3, BR-V4); empty when they agree."""
    problems = []
    for name in sorted(lock):
        if name not in installed:
            problems.append(f"{name}: missing ({lock[name]} locked)")
        elif installed[name] != lock[name]:
            problems.append(f"{name}: {installed[name]} installed, {lock[name]} locked")
    if not allow_extra:
        problems.extend(f"{name}: {installed[name]} installed, not in the lock" for name in sorted(set(installed) - set(lock)))
    return problems


def check_extras_lines(text: str, source: str = "requirements.txt") -> tuple[list[str], list[str]]:
    """The normalized names of a product's extras file and its problems (BR-E2 to BR-E9)."""
    names: list[str] = []
    problems: list[str] = []
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if line.startswith("#"):
            continue
        line = INLINE_COMMENT.sub("", line).strip()
        if not line:
            continue
        if line.startswith("-"):
            problems.append(f"{source}:{number}: options are not allowed")
        elif "@" in line or "://" in line or line.startswith((".", "/", "~")) or line.endswith("\\"):
            problems.append(f"{source}:{number}: URLs and paths are not allowed")
        elif not REQUIREMENT.fullmatch(line):
            problems.append(f"{source}:{number}: not a plain requirement")
        else:
            name = normalize_name(NAME_RE.match(line).group(0))
            if name in PLATFORM_MANAGED:
                problems.append(f"{source}:{number}: {name} is provided by the platform")
            elif name in names:
                problems.append(f"{source}:{number}: {name} appears twice")
            else:
                names.append(name)
    if len(names) > MAX_EXTRAS_REQUIREMENTS:
        problems.append(f"{source}: more than {MAX_EXTRAS_REQUIREMENTS} requirements")
    return names, problems


def read_extras(path: Path) -> tuple[list[str], list[str]]:
    """Read and check an extras file (BR-E1): UTF-8, at most 64 KiB."""
    data = path.read_bytes()
    if len(data) > MAX_EXTRAS_BYTES:
        return [], [f"{path.name}: larger than {MAX_EXTRAS_BYTES // 1024} KiB"]
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return [], [f"{path.name}: not UTF-8"]
    return check_extras_lines(text, path.name)


def platform_args() -> list[str]:
    """pip target arguments for the Spark runtime: CPython 3.10 on aarch64 with glibc 2.31 or older."""
    args = ["--python-version", PYTHON_VERSION, "--implementation", "cp", "--abi", "cp310"]
    for tag in PLATFORM_TAGS:
        args += ["--platform", tag]
    return args


def pip_env() -> dict[str, str]:
    """The environment for pip and checks: no PYTHONPATH (it would list /opt/spark's pyspark) and no PIP_* settings."""
    return {key: value for key, value in os.environ.items() if key != "PYTHONPATH" and not key.startswith("PIP_")}


def installed_set(python: str) -> tuple[str, dict[str, str]]:
    """The interpreter's Python version and its ``pip freeze`` (BR-V2)."""
    env = pip_env()
    version = subprocess.run(
        [python, "-c", "import sys; print('%d.%d' % sys.version_info[:2])"],
        env=env, check=True, capture_output=True, text=True,
    ).stdout.strip()
    freeze = subprocess.run(
        [python, "-m", "pip", "freeze", "--disable-pip-version-check"],
        env=env, check=True, capture_output=True, text=True,
    ).stdout
    return version, parse_freeze(freeze)


def check_venv(python: str, lock: dict[str, str], allow_extra: bool = False) -> tuple[list[str], dict[str, str]]:
    """Problems of an interpreter against the lock (BR-V1 to BR-V4), and its packages beyond the lock."""
    version, installed = installed_set(python)
    problems = [] if version == PYTHON_VERSION else [f"Python {version}, not {PYTHON_VERSION}"]
    problems += compare(lock, installed, allow_extra)
    extra = {name: installed[name] for name in sorted(set(installed) - set(lock))}
    return problems, extra


def _pip(python: str, *args: str) -> int:
    return subprocess.run([python, "-m", "pip", *args], env=pip_env(), check=False).returncode


def _report_installs(report: Path) -> list[tuple[str, str]]:
    items = json.loads(report.read_text(encoding="utf-8")).get("install", [])
    return [(item["metadata"]["name"], item["metadata"]["version"]) for item in items]


def _load_lock(path: Path) -> tuple[dict[str, str], list[str]]:
    try:
        return parse_lock(path.read_text(encoding="utf-8"), path.name)
    except OSError as error:
        return {}, [f"{path}: cannot read the lock ({error.strerror})"]


def _extras_path(given: str | None) -> Path:
    path = Path(given or "requirements.txt").expanduser()
    # A folder stands for its requirements.txt; a folder named requirements.txt is refused later.
    return path / "requirements.txt" if path.is_dir() and path.name != "requirements.txt" else path


def _target_projects(target: Path) -> dict[str, Path]:
    """{normalized name: dist-info folder} of the projects installed in a --target folder."""
    projects = {}
    for info in target.glob("*.dist-info"):
        name = None
        metadata = info / "METADATA"
        if metadata.is_file():
            for line in metadata.read_text(encoding="utf-8", errors="replace").splitlines():
                if line.startswith("Name:"):
                    name = line.split(":", 1)[1].strip()
                    break
        if name:
            projects[normalize_name(name)] = info
    return projects


def remove_from_target(target: Path, info: Path) -> None:
    """Remove one project from a --target folder by its RECORD, staying inside the folder (BR-J5)."""
    root = target.resolve()
    record = info / "RECORD"
    paths = []
    if record.is_file():
        for line in record.read_text(encoding="utf-8", errors="replace").splitlines():
            relative = line.split(",", 1)[0].strip()
            if relative:
                paths.append((root / relative).resolve())
    for path in paths:
        if path.is_relative_to(root) and path != root and path.is_file():
            path.unlink()
    for directory in sorted({p.parent for p in paths}, key=lambda p: len(p.parts), reverse=True):
        while directory.is_relative_to(root) and directory != root and directory.is_dir() and not any(directory.iterdir()):
            directory.rmdir()
            directory = directory.parent
    if info.is_dir():
        shutil.rmtree(info)


def _print_problems(problems: list[str]) -> int:
    for problem in problems:
        print(problem)
    print(f"{len(problems)} problem(s)")
    return 1


def cmd_check_lock(args: argparse.Namespace) -> int:
    lock, problems = _load_lock(Path(args.lock_file))
    if problems:
        return _print_problems(problems)
    print(f"OK: {len(lock)} locked package(s)")
    return 0


def cmd_check_venv(args: argparse.Namespace) -> int:
    lock, problems = _load_lock(Path(args.lock))
    if problems:
        return _print_problems(problems)
    problems, extra = check_venv(args.python, lock, args.allow_extra)
    if problems:
        return _print_problems(problems)
    print(f"OK: Python {PYTHON_VERSION}, {len(lock)} locked package(s) at their locked versions")
    if extra:
        print("Additional packages: " + ", ".join(f"{name}=={version}" for name, version in extra.items()))
    return 0


def cmd_check_extras(args: argparse.Namespace) -> int:
    path = Path(args.file)
    if not path.is_file():
        print(f"{path}: not a file")
        return 1
    lock, problems = _load_lock(Path(args.lock))
    names, line_problems = read_extras(path)
    problems += line_problems
    if problems:
        return _print_problems(problems)
    if not names:
        print(f"OK: {path.name} has no requirements")
        return 0
    with tempfile.TemporaryDirectory(prefix="lakehouse-extras-") as work:
        report = Path(work) / "report.json"
        status = _pip(
            sys.executable, "install", "--dry-run", "--ignore-installed", "--quiet", "--only-binary=:all:",
            *platform_args(), "--target", str(Path(work) / "target"), "--report", str(report),
            "--constraint", args.lock, "--requirement", str(path), *PIP_COMMON,
        )
        if status != 0:
            print(f"{path.name} does not resolve against the platform lock with prebuilt aarch64 wheels for Python {PYTHON_VERSION} (see pip's message above).")
            return 1
        added = [f"{name}=={version}" for name, version in _report_installs(report) if normalize_name(name) not in lock]
    print(f"OK: {path.name} resolves against the platform lock ({len(names)} requirement(s))")
    if added:
        print("Would add: " + ", ".join(sorted(added, key=str.lower)))
    return 0


def _install_into_venv(path: Path, lock_path: str, lock: dict[str, str]) -> int:
    status = _pip(
        sys.executable, "install", "--quiet", "--only-binary=:all:",
        "--constraint", lock_path, "--requirement", str(path), *PIP_COMMON,
    )
    if status != 0:
        print(f"Installing {path.name} failed (see pip's message above).")
        return 1
    problems, extra = check_venv(sys.executable, lock, allow_extra=True)
    if problems:
        return _print_problems(problems)
    print("Installed: " + (", ".join(f"{name}=={version}" for name, version in extra.items()) or "nothing new"))
    return 0


def _install_into_target(path: Path, lock_path: str, lock: dict[str, str], target: Path, reset: bool) -> int:
    stamp = target / STAMP_NAME
    lock_hash = hashlib.sha256(Path(lock_path).read_bytes()).hexdigest()
    contents = [entry for entry in target.iterdir() if entry.name != STAMP_NAME] if target.is_dir() else []
    if contents and not stamp.is_file():
        print(f"{target} holds files this command did not install; move them away first.")
        return 1
    if reset and target.is_dir():
        shutil.rmtree(target)
        contents = []
    elif contents and stamp.read_text(encoding="utf-8").strip() != lock_hash:
        print("The platform lock changed since these packages were installed; rerun with --reset.")
        return 1
    target.mkdir(parents=True, exist_ok=True)
    # The venv's .pth file adds the folder to sys.path, so pip sees what is already there.
    with tempfile.TemporaryDirectory(prefix="lakehouse-extras-") as work:
        report = Path(work) / "report.json"
        status = _pip(
            sys.executable, "install", "--dry-run", "--quiet", "--only-binary=:all:", "--report", str(report),
            "--constraint", lock_path, "--requirement", str(path), *PIP_COMMON,
        )
        if status != 0:
            print(f"{path.name} does not resolve against the platform lock (see pip's message above).")
            return 1
        wanted = _report_installs(report)
    stamp.write_text(lock_hash + "\n", encoding="utf-8")
    if not wanted:
        print(f"Nothing to add: {path.name} is already satisfied.")
        return 0
    present = _target_projects(target)
    for name, _ in wanted:
        if normalize_name(name) in present:
            remove_from_target(target, present[normalize_name(name)])
    status = _pip(
        sys.executable, "install", "--quiet", "--no-deps", "--upgrade", "--only-binary=:all:", "--target", str(target),
        "--constraint", lock_path, *[f"{name}=={version}" for name, version in wanted], *PIP_COMMON,
    )
    if status != 0:
        print(f"Installing {path.name} failed (see pip's message above).")
        return 1
    problems, _ = check_venv(sys.executable, lock, allow_extra=True)
    if problems:
        return _print_problems(problems)
    print("Installed: " + ", ".join(f"{name}=={version}" for name, version in wanted))
    print("Restart the kernel to use them.")
    return 0


def cmd_install_extras(args: argparse.Namespace) -> int:
    path = _extras_path(args.file)
    if not path.exists():
        print(f"No {path.name}; nothing to install.")
        return 0
    if not path.is_file():
        print(f"{path}: not a file")
        return 1
    lock, problems = _load_lock(Path(args.lock))
    names, line_problems = read_extras(path)
    problems += line_problems
    if problems:
        return _print_problems(problems)
    if not names:
        print(f"{path.name} has no requirements; nothing to install.")
        return 0
    if args.target:
        return _install_into_target(path, args.lock, lock, Path(args.target).expanduser(), args.reset)
    return _install_into_venv(path, args.lock, lock)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="workload_python.py", description="The shared workload Python environment.")
    commands = parser.add_subparsers(dest="command", required=True)
    check_lock = commands.add_parser("check-lock", help="check a lock file's format")
    check_lock.add_argument("lock_file")
    check_lock.set_defaults(run=cmd_check_lock)
    venv = commands.add_parser("check-venv", help="check that an interpreter holds exactly the lock")
    venv.add_argument("python")
    venv.add_argument("--lock", required=True)
    venv.add_argument("--allow-extra", action="store_true", help="allow packages beyond the lock")
    venv.set_defaults(run=cmd_check_venv)
    extras = commands.add_parser("check-extras", help="check a product requirements.txt against the lock")
    extras.add_argument("file")
    extras.add_argument("--lock", required=True)
    extras.set_defaults(run=cmd_check_extras)
    install = commands.add_parser("install-extras", help="install a product requirements.txt, constrained by the lock")
    install.add_argument("file", nargs="?", help="requirements.txt, or a folder holding one (default: ./requirements.txt)")
    install.add_argument("--lock", required=True)
    install.add_argument("--target", help="install into this folder instead of the running venv")
    install.add_argument("--reset", action="store_true", help="with --target: empty the folder first")
    install.set_defaults(run=cmd_install_extras)
    args = parser.parse_args(argv)
    if getattr(args, "reset", False) and not args.target:
        parser.error("--reset needs --target")
    return args.run(args)


if __name__ == "__main__":
    raise SystemExit(main())
